"""Writes tools/ida/apply_names.idc from tools/ida/names.txt.

Lines: `address name [comment]` for functions, `data address name
[comment]` for globals. Run: python3 -I tools/ida/gen_names.py
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
out = ["// Generated by gen_names.py from names.txt. Do not edit.",
       "// Run in IDA: File > Script file...", "#include <idc.idc>", "", "static main()", "{"]
for line in open(os.path.join(here, "names.txt")):
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    parts = line.split(None, 3 if line.startswith("data ") else 2)
    if parts[0] == "data":
        addr, name = parts[1], parts[2]
    else:
        addr, name = parts[0], parts[1]
    out.append(f'    set_name({addr}, "{name}", SN_NOWARN);')
out += ['    msg("names applied\\n");', "}", ""]
open(os.path.join(here, "apply_names.idc"), "w").write("\n".join(out))
