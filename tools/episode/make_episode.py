"""Builds the episode (the menu's Episode 3X99): the disc scripts of
tests/play, from a new game to the credits, as one script compiled into
the program (src/games/xfiles/episode.c). Comments and checks are left
out; the steps are the story's happy path.

  make_episode.py [tests/play/disc7.txt] [src/games/xfiles/episode.c]
"""
import os
import sys

DROP = {'expect', 'state', 'var', 'text', 'assets', 'items', 'route', 'gate', 'reach', 'shot', 'need'}


def flatten(path, out):
    base = os.path.dirname(path)
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            words = line.split()
            if words[0] == 'include':
                flatten(os.path.join(base, words[1]), out)
            elif words[0] not in DROP:
                out.append(' '.join(words))


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'tests/play/disc7.txt'
    dst = sys.argv[2] if len(sys.argv) > 2 else 'src/games/xfiles/episode.c'
    steps = []
    flatten(src, steps)
    with open(dst, 'w', encoding='utf-8') as f:
        f.write('/* SPDX-License-Identifier: GPL-3.0-or-later\n * Copyright (C) 2026 xesf */\n')
        f.write('/* Generated by tools/episode/make_episode.py from tests/play/%s and the\n' % os.path.basename(src))
        f.write(' * scripts it includes: the steps of the story from a new game to the\n')
        f.write(' * credits. Do not edit; run the tool again. */\n')
        f.write('#include "games/xfiles/episode.h"\n\n')
        f.write('const char *const g_episode_steps[] = {\n')
        for s in steps:
            f.write('    "%s",\n' % s.replace('\\', '\\\\').replace('"', '\\"'))
        f.write('};\n\nconst int g_episode_step_count = (int)(sizeof(g_episode_steps) / sizeof(g_episode_steps[0]));\n')
    print('%d steps -> %s' % (len(steps), dst))
    return 0


if __name__ == '__main__':
    sys.exit(main())
