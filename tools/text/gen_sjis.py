"""Writes src/core/xf_sjis_table.h: the Shift-JIS (Windows code page 932)
double-byte characters as Unicode, from Python's cp932 codec.

    python3 tools/text/gen_sjis.py > src/core/xf_sjis_table.h
"""
LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = range(0x40, 0xFD)

print("/* SPDX-License-Identifier: GPL-3.0-or-later\n * Copyright (C) 2026 xesf */")
print("/* Generated by tools/text/gen_sjis.py from the cp932 mapping: the")
print(" * Unicode code point of each double-byte character, 0 where none. */")
print("static const u16 g_sjis_double[%d][%d] = {" % (len(LEADS), len(TRAILS)))
for lead in LEADS:
    row = []
    for trail in TRAILS:
        try:
            ch = bytes([lead, trail]).decode("cp932")
            row.append(ord(ch) if len(ch) == 1 and ord(ch) < 0x10000 else 0)
        except UnicodeDecodeError:
            row.append(0)
    print("    { /* 0x%02X */" % lead)
    for i in range(0, len(row), 12):
        print("        " + ", ".join("0x%04X" % v for v in row[i:i + 12]) + ",")
    print("    },")
print("};")
